export const LANGUAGES = [
  { id: 'auto', labelKey: 'options.languageAuto' },
  { id: 'en', label: 'English' },
  { id: 'ar', label: 'العربية' },
];

export const RTL_LANGUAGES = new Set(['ar']);

let current = 'en';

export function resolveLanguage(setting) {
  if (setting && setting !== 'auto') return STRINGS[setting] ? setting : 'en';
  const browser = (navigator.language || 'en').toLowerCase();
  return browser.startsWith('ar') ? 'ar' : 'en';
}

export function getLanguage() {
  return current;
}

export function isRtl() {
  return RTL_LANGUAGES.has(current);
}

/** Translate a key, substituting $1, $2… positional arguments. */
export function t(key, ...args) {
  const template = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  return args.length
    ? template.replace(/\$(\d+)/g, (_, index) => args[Number(index) - 1] ?? '')
    : template;
}

/**
 * Applies a language to the document: sets lang/dir and fills every element
 * carrying a data-i18n attribute. Safe to call repeatedly.
 */
export function applyLanguage(setting, root = document) {
  current = resolveLanguage(setting);
  const rtl = isRtl();

  if (root === document) {
    document.documentElement.lang = current;
    document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  }

  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
  }
  return current;
}

/** Locale for date/number formatting. */
export function locale() {
  return current === 'ar' ? 'ar-SA' : 'en-US';
}
